-- REQUERIMIENTO 1
SELECT PATENTE,
       COUNT(*) AS CANTIDAD_REPARACIONES,
       SUM(HORAS_TRABAJO) AS HORAS_EN_REPARACION
FROM REPARACION
GROUP BY PATENTE
ORDER BY CANTIDAD_REPARACIONES DESC;

-- REQUERIMIENTO 2
CREATE OR REPLACE VIEW v_reparaciones_2012 AS
SELECT M.NOMBRE || ' ' || M.APELLIDO AS MECANICO,
       R.PATENTE,
       R.FECHA_REPARAC AS FECHA_REPARACION,
       R.VALOR_REPARAC AS MONTO_REPARACION
FROM REPARACION R
JOIN MECANICO M ON R.COD_MEC = M.COD_MEC
WHERE EXTRACT(YEAR FROM R.FECHA_REPARAC) = 2012
ORDER BY R.FECHA_REPARAC ASC;
SELECT * FROM v_reparaciones_2012;

--REQUERIMIENTO 3
SELECT MARCA,
       PATENTE,
       VALOR_COMPRA,
       CASE
         WHEN VALOR_COMPRA >= 8000000 THEN 'GRANDE'
         WHEN VALOR_COMPRA >= 6500000 THEN 'MEDIO'
         WHEN VALOR_COMPRA >= 5700000 THEN 'NORMAL'
         ELSE 'PEQUEÑO'
       END AS CLASIFICACION_VEHICULO
FROM VEHICULO
ORDER BY VALOR_COMPRA ASC;

--REQUERIMIENTO 4
CREATE OR REPLACE VIEW V_REPARACIONES AS
SELECT M.NOMBRE || ' ' || M.APELLIDO AS NOMBRE_COMPLETO,
       R.TRABAJO AS DESCRIPCION,
       R.FECHA_REPARAC AS FECHA_REPARACION,
       R.FECHA_REPARAC + 7 AS FECHA_RETIRO,
       V.PATENTE,
       V.MARCA
FROM REPARACION R
JOIN MECANICO M ON R.COD_MEC = M.COD_MEC
JOIN VEHICULO V ON R.PATENTE = V.PATENTE;