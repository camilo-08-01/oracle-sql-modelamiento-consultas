CONSTRAINT FK_TURNO_ESCUELA FOREIGN KEY (ESCUELA_nombre)
REFERENCES ESCUELA (nombre),
CONSTRAINT FK_TURNO_PROFESOR FOREIGN KEY (PROFESOR_numero_folio)
REFERENCES PROFESOR (numero_folio)
);

