CONSTRAINT PK_ESCUELA PRIMARY KEY (nombre),
CONSTRAINT FK_ESCUELA_COMUNA FOREIGN KEY (COMUNA_codigo)
REFERENCES COMUNA (codigo),
CONSTRAINT FK_ESCUELA_TIPO_ESCUELA FOREIGN KEY (TIPO_ESCUELA_codigo)
REFERENCES TIPO_ESCUELA (codigo),
CONSTRAINT FK_ESCUELA_DIRECTOR FOREIGN KEY (DIRECTOR_rut)
REFERENCES DIRECTOR (rut)
);

