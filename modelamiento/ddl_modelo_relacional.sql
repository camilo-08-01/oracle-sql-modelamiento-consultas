ESTADO_CIVIL_codigo NUMBER(6) NOT NULL,
COMUNA_codigo NUMBER(6) NOT NULL,
CONSTRAINT PK_DIRECTOR PRIMARY KEY (rut),
CONSTRAINT FK_DIRECTOR_PROFESION FOREIGN KEY (PROFESION_codigo)
REFERENCES PROFESION (codigo),
CONSTRAINT FK_DIRECTOR_ESTADO_CIVIL FOREIGN KEY (ESTADO_CIVIL_codigo)
REFERENCES ESTADO_CIVIL (codigo),
CONSTRAINT FK_DIRECTOR_COMUNA FOREIGN KEY (COMUNA_codigo)
REFERENCES COMUNA (codigo)
);

