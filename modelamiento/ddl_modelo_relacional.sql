-- CREACIÓN TABLA PROFESOR
CREATE TABLE PROFESOR
(
numero_folio NUMBER(10),
run NUMBER(12) NOT NULL,
dvrun VARCHAR2(1) NOT NULL,
pnombre VARCHAR2(20) NOT NULL,
snombre VARCHAR2(20),
apaterno VARCHAR2(20) NOT NULL,
amaterno VARCHAR2(20) NOT NULL,
calle VARCHAR2(20) NOT NULL,
numero NUMBER(6) NOT NULL,
COMUNA_codigo NUMBER(6) NOT NULL,
LUGAR_ESTUDIO_codigo NUMBER(6),
ESPECIALIDAD_codigo NUMBER(6) NOT NULL,
CONSTRAINT PK_PROFESOR PRIMARY KEY (numero_folio),
CONSTRAINT FK_PROFESOR_COMUNA FOREIGN KEY (COMUNA_codigo)
REFERENCES COMUNA (codigo),
CONSTRAINT FK_PROFESOR_LUGAR_ESTUDIO FOREIGN KEY (LUGAR_ESTUDIO_codigo)
REFERENCES LUGAR_ESTUDIO (codigo),
CONSTRAINT FK_PROFESOR_ESPECIALIDAD FOREIGN KEY (ESPECIALIDAD_codigo)
REFERENCES ESPECIALIDAD(codigo)
);

